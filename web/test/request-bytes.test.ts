import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { ROOT, sim } from './helpers'
import { requestBytes } from '../functions/_lib/nearai'
import { sha256Hex } from '../src/game/chain/signature'
import { utf8 } from '../src/game/chain/bytes'

const golden = JSON.parse(readFileSync(join(__dirname, 'fixtures/request-golden.json'), 'utf8'))
const escapeCases: { input: string; escaped: string }[] = JSON.parse(readFileSync(join(ROOT, 'vectors/escape-cases.json'), 'utf8'))

describe('request bytes equal the Rust request_parts (golden generated by native Rust)', () => {
  const s = sim()
  it('prefix and suffix match byte for byte (sha256 and length)', () => {
    const p = s.requestParts(golden.model)
    expect(sha256Hex(utf8(p.prefix))).toBe(golden.prefix_sha256)
    expect(sha256Hex(utf8(p.suffix))).toBe(golden.suffix_sha256)
    expect(utf8(p.prefix).length).toBe(golden.prefix_len)
    expect(utf8(p.suffix).length).toBe(golden.suffix_len)
    expect(p.rulebook_hash).toBe(golden.rulebook_hash)
  })
  it.each(golden.cases as { sentence: string; request_len: number; request_sha256: string; escaped: string }[])('request for $sentence is identical to the Rust bytes', (c) => {
    const body = requestBytes(s, golden.model, c.sentence)
    expect(body.length).toBe(c.request_len)
    expect(sha256Hex(body)).toBe(c.request_sha256)
    expect(JSON.stringify(c.sentence).slice(1, -1)).toBe(c.escaped)
    expect(JSON.parse(new TextDecoder().decode(body)).messages.at(-1).content).toBe(`Sentence: ${c.sentence}`)
  })
  it('the wasm build_request equals prefix + escape + suffix', () => {
    for (const c of golden.cases) expect(s.buildRequest(golden.model, c.sentence)).toBe(new TextDecoder().decode(requestBytes(s, golden.model, c.sentence)))
  })
  it('JS escaping equals the recorded node JSON.stringify reference for hostile strings', () => {
    for (const c of escapeCases) expect(JSON.stringify(c.input).slice(1, -1)).toBe(c.escaped)
  })
})
